# ---------- 促音便・半濁音化の一般規則（2026-08-21）----------
# 旧実装は助数詞ごとに「特殊読みの表」を持ち、表に無い数（40歳・第41回・100件…）は
# 素の読み＋助数詞になっていた＝「よんじゅうさい」「よんじゅういちかい」。
# 日本語の音便は数の1の位（と十/百の位）で決まる規則なので、表ではなく規則で作る。
_HA2PA = {"は": "ぱ", "ひ": "ぴ", "ふ": "ぷ", "へ": "ぺ", "ほ": "ぽ"}
_HA2BA = {"は": "ば", "ひ": "び", "ふ": "ぶ", "へ": "べ", "ほ": "ぼ"}
_KA_ROW, _SA_ROW, _TA_ROW = "かきくけこ", "さしすせそ", "たちつてと"

# 音便を起こす助数詞（表記）だけを明示する。施設・品目のように慣用が割れるものは入れない。
EUPHONIC = {"回", "歳", "件", "期", "種", "床", "か月", "ヶ月", "カ月", "箇所", "か所", "対"}


def _euphonic(n: int, base: str) -> str:
    """数nと助数詞の読みbaseから、音便込みの読みを作る。規則外はNoneを返す。"""
    head = base[0]
    ka, sa, ta = head in _KA_ROW, head in _SA_ROW, head in _TA_ROW
    ha = head in _HA2PA
    if not (ka or sa or ta or ha):
        return None
    ones = n % 10
    pre = num_to_yomi(str(n - ones)) if n - ones else ""

    def _p(b):                      # は行→ぱ行
        return _HA2PA[b[0]] + b[1:] if ha else b

    if ones == 1 and (ka or sa or ta or ha):
        return pre + "いっ" + _p(base)
    if ones == 6 and (ka or ha):
        return pre + "ろっ" + _p(base)
    if ones == 8:
        return pre + "はっ" + _p(base)
    if ones == 3 and ha:
        return pre + "さん" + _HA2BA[head] + base[1:]
    if ones == 0 and n:
        # 末尾が「じゅう」→じゅっ、「ひゃく」→ひゃっ（ひゃっはか行・は行のみ）
        y = num_to_yomi(str(n))
        if y.endswith("じゅう"):
            return y[:-3] + "じゅっ" + _p(base)
        if y.endswith("ひゃく") and (ka or ha):
            return y[:-3] + "ひゃっ" + _p(base)
        return None
    return None


