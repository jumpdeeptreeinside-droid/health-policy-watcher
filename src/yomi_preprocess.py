# ---------- かなに開くか、数字のまま渡すか（2026-08-21・実測で決定）----------
# VOICEPEAK+Whisperで実台本24文をA/Bした結果:
#   生の数字のまま 53/56一致 ／ 全部かなに展開 38/56一致
# 長いかな列はVOICEPEAKが拗音を落とす（「にひゃくごじゅうなな」→"に・ひやく・ごじゅうなな"）。
# 緑さんメモの「10→じゆう」「100→ひやく」はまさにこれで、かな展開そのものが原因だった。
# ＝短い不規則読み（ひとり・ようか・よんじゅっさい）だけかなにし、長い数字は数字のまま渡す。
MAX_MORA = 8
_SMALL_KANA = set("ゃゅょぁぃぅぇぉっャュョァィゥェォッ")
# 「数字のまま渡す」と決めた数はここで私用領域に退避する。そうしないと後続の規則が
# 桁の一部だけをかなに変えて「257.はち床」のような混ざり方をする（2026-08-21）。
_PROTECT = {str(i): chr(0xE000 + i) for i in range(10)}
_UNPROTECT = {v: k for k, v in _PROTECT.items()}


def _mora(kana: str) -> int:
    return sum(1 for c in kana if c not in _SMALL_KANA)


def _protect_digits(raw: str) -> str:
    return "".join(_PROTECT.get(c, c) for c in raw)


def unprotect_digits(text: str) -> str:
    return "".join(_UNPROTECT.get(c, c) for c in text)


def _short(kana: str, raw: str) -> str:
    """短い不規則読みだけかなにし、長い数はVOICEPEAK自身の数値読みに任せる。
    小数は長さに関係なくかなにしない＝実測で「きゅうてんきゅうにち」(9.9日)が
    「起遊転休日」と読まれ、生の「9.9日」は正しく読まれた（2026-08-21）。"""
    if "." in raw:
        return _protect_digits(raw)
    return kana if _mora(kana) <= MAX_MORA else _protect_digits(raw)


