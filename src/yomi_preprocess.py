    for src, must, must_not in CASES:
        out = to_yomi(src)
        if must and must not in out:
            print(f"  NG {src!r}\n     期待 {must!r} を含む → {out!r}"); ng += 1
        elif must_not and must_not in out:
            print(f"  NG {src!r}\n     {must_not!r} が残っている → {out!r}"); ng += 1
    if not CASES:
        print("  ⚠ テストケースが0件＝検査が空振りしている"); ng += 1
    print(f"{len(CASES) - ng}/{len(CASES)} 合格" + ("" if ng else " ✅"))
    return ng


