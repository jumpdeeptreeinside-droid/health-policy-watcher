_HYAKU_KANA_COUNTERS = {"床": "しょう"}
_HYAKU_KANA_RE = re.compile(r"(?<![0-9,.])([0-9][0-9,]*)(" +
                            "|".join(_HYAKU_KANA_COUNTERS) + ")")


def fix_hyaku_kana_counters(t: str) -> str:
    def rep(m):
        raw, unit = m.group(1), m.group(2)
        n = int(raw.replace(",", ""))
        if n % 100 == 0 and (n % 1000) // 100:    # 末尾がN00 → 助数詞が「ひゃく」に貼りつく
            return raw + _HYAKU_KANA_COUNTERS[unit]
        return m.group(0)
    return _HYAKU_KANA_RE.sub(rep, t)


def to_yomi(text: str) -> str:
    """表示用テキスト → 読み上げ用テキスト"""
    t = text
    # 全角→半角（数字・英字・記号）。全角の「，．」が漏れていたため
    # 「１，８０３人→1，はっぴゃくさんにん」「２７．４日→27．4日」と壊れていた（2026-08-04 修正）。
    t = t.translate(str.maketrans("０１２３４５６７８９ＡＢＣＤＥＦＧＨＩＪＫＬＭＮＯＰＱＲＳＴＵＶＷＸＹＺ％，．",
                                   "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ%,."))

    # 台本側で助詞「の」が of / 의 に化けている場合は日本語へ戻す（落とす前に）
    t, _fixed = restore_particles(t)

    # 他の文字体系（ハングル等）は読み上げ不能なので落とす
    t, _dropped = strip_foreign(t)

    # 既知略語（長いものから・英数字に挟まれた部分一致は置換しない）
    t = sub_acronyms(t)

    # 難読語（人の試聴指摘由来）を先に確定させる
    t = sub_hardwords(t)

    # 統計表記の「671千人」＝67万1千人。数値に直してから読む（緑さんメモ 2026-08-21）
    t = re.sub(r"(?<![0-9,])([0-9]{1,3}(?:,[0-9]{3})+|[0-9]+)\.([0-9]+)千",
               lambda m: str(int(round(float(m.group(1).replace(",", "") + "." + m.group(2)) * 1000))), t)
    t = re.sub(r"(?<![0-9,.])([0-9]{1,3}(?:,[0-9]{3})+|[0-9]{2,})千",
               lambda m: str(int(m.group(1).replace(",", "")) * 1000), t)

    # 数字につく助数詞「人」は「名」にして、人の不規則読みをまとめて避ける（2026-09-20）
    t = counter_nin_to_mei(t)

    t = fix_hyaku_counters(t)   # 残るのは「枚」。末尾のN百だけかなにする（上のコメント参照）
    # 床・歳も同じ型で詰まる（200床→にひゃっしょう）。こちらは数字を残して助数詞だけかなに。
    t = fix_hyaku_kana_counters(t)

    # ── 数字はかなに開かない（2026-08-21・実測で方針転換）──────────────
    # 2026-08-04に「残った整数はすべて読みに展開する」としたが、これが誤読の発生源だった。
    #   ・実台本24文のA/B: 生の数字53/56一致 vs 全かな展開38/56一致
    #   ・「ろっぴゃくじゅうなな」(617)→"6比約17"、「じゅうにん」(10人)→"自由人"と崩れる
    #   ・音声長で直接確かめると、VOICEPEAKは自前で 8月8日=ようか / 20日=はつか /
    #     40歳=よんじゅっさい / 1人=ひとり と正しく読む（かな版と同じ長さ・誤読版とは別長さ）
    # ＝助数詞の不規則読みはVOICEPEAK自身が持っている。かな層は利点なしで崩れだけ持ち込む。
    # 触ってよいのは「表記そのものが読めない」統計表記だけ。
    #
    # 「29201百万円」＝統計表の百万円単位。字面のまま読まれるので、人が言う形
    # 「292億100万円」に組み直す（出力は数字のまま＝VOICEPEAKの数値読みに任せる）。
    t = re.sub(r"(?<![0-9,.])([0-9]{1,3}(?:,[0-9]{3})+|[0-9]+)(?:\.([0-9]+))?\s*百万",
               lambda m: group_units(int(round(float((m.group(1).replace(",", "")) +
                                                     ("." + m.group(2) if m.group(2) else "")) * 10**6))), t)

    # 「671千人」「3580.5千人」＝統計表の千人単位。数値に直す（出力は数字のまま）。
    t = re.sub(r"(?<![0-9,])([0-9]{1,3}(?:,[0-9]{3})+|[0-9]+)\.([0-9]+)千",
               lambda m: str(int(round(float(m.group(1).replace(",", "") + "." + m.group(2)) * 1000))), t)
    t = re.sub(r"(?<![0-9,.])([0-9]{1,3}(?:,[0-9]{3})+|[0-9]{2,})千",
               lambda m: str(int(m.group(1).replace(",", "")) * 1000), t)

    # 「31日」だけはVOICEPEAKが「さんじゅうしちにち」と読む（＝37日に聞こえる）。
    # 21日/11日/1日/8日/20日は正しく読めるので、31日に限ってかなを当てる。
    # 「令和8年5月31日」で再現・かな版は正しいことを実測で確認（2026-08-21）。
    # 「5月31日」だけVOICEPEAKが「ごがつさんじゅうしちにち」と読む（＝37日に聞こえる）。
    # 総当たりで実測した結果、直せるのは月ごとかなにした形だけだった:
    #   3月31日 / 12月31日 … 数字のままで正しい（かなにすると「自由2月」等に崩れる）
    #   5月31日           … 数字のままだと37日・「ごがつさんじゅういちにち」なら正しい
    #   日だけかなにすると直前の月が数字と切り離されて「さつき」と読まれる
    # 過剰に一般化せず、確認できた組み合わせだけ当てる。他の月で誤読が出たらここに足す。
    t = re.sub(r"(?<![0-9])5月31日", "ごがつさんじゅういちにち", t)

    # 数字につく「日」は必ず「にち」で読む（2026-09-25 指定 → 2026-09-27 小数と3桁以上も）。
    # VOICEPEAKは16日→「じゅうむいか」、1日→「ついたち」のように和語読みを引きずる。
    # 暦としては むいか/ついたち が正しい場面もあるが、この番組は統計の読み上げが主で
    # 「1日平均」「6日時点」を和語で読まれると意味が取りにくい。
    # 🔴 最初は二桁の整数だけにしていたが、いちばん多い「平均在院日数」が
    #    9.9日・254.4日・114.1日と**小数**なので素通りし、「〜か」のままだった
    #    （2026-09-27 試聴指摘）。小数・カンマ・桁数を問わず、数字の後の日は全部にち。
    t = re.sub(r"(?<![0-9,.])([0-9][0-9,]*(?:\.[0-9]+)?)日", lambda m: m.group(1) + "にち", t)

    # 数字につく「胎」（死産数の単位）は「たい」で読む（2026-10-26 試聴指摘・翔太さん）。
    # VOICEPEAKは漢字のままだと「はら」と読む。実測（単文を合成してwhisperで起こした）:
    #   「1238胎」→"1238ハラ"／「68胎」→"68原"／裸の「胎です」→"腹です"
    #   「1238たい」「1238タイ」→どちらも"1238体"＝たい と正しく読む（拗音がないのでかなで足りる）
    #   本番のチャンクそのまま（…3368めい…1238たいで…68たい…）でも"1,238体""68体"と読めた
    #   「1万たい」→"1万体"（万の直後の形も確認済み）
    # 🔴 1文字の「胎」を無条件に置き換えてはいけない。「胎児」が「たい児」になる
    #    （シート側の1文字指摘を vet_overrides が弾くのと同じ理由）。
    #    数字（＋万/億/兆）の直後＝助数詞の位置だけに当てる。「胎児」は漢字のまま正しく読めた（実測）。
    t = re.sub(r"([0-9](?:万|億|兆)?)胎", lambda m: m.group(1) + "たい", t)

    t = re.sub(r"\s*[%％]", "パーセント", t)

    # 範囲（小数〜小数＋パーセント）は、**両側**をまとめて開く。
    # 🔴 2026-11-04 翔太さんの耳：「9.1からきゅうてんごパーセント」の**左の 9.1** が
    #    「くてんいち」と読まれていた（見本の2番）。右側だけ開く形では、左に残った
    #    4／7／9 の誤読がそのまま出る。＝範囲の中にある1桁の 4・7・9 の小数は、
    #    左右どちらでも開く（翔太さんの決定＝見本の11番のB）。
    # 🔑 1桁の 4・7・9 以外（3.2 など）は開かない＝誤読が報告されていないものは触らない。
    # 🔑 この規則は下の「〜」→「から」より先に当てる（先に開くと「〜」が記号で残る）。
    # 片側が2桁以上（4.8〜12.3％）でも、開く側だけ開く＝範囲ごと取りこぼさない。
    def _range_pct(m):
        def side(d, dec):
            return decimal_to_yomi(d, dec) if len(d) == 1 and d in "479" else f"{d}.{dec}"
        return side(m.group(1), m.group(2)) + "から" + side(m.group(3), m.group(4))
    t = re.sub(r"(?<![0-9.,])([0-9]+)\.([0-9]+)\s*[〜~～]\s*([0-9]+)\.([0-9]+)(?=パーセント)",
               _range_pct, t)

    # 範囲の「〜」は記号のままだと読まれないので「から」に開く。
    # 🔴 2026-11-04 ミハルの指摘：この規則は**小数をかなに開く規則より先**に置くこと。
    #    逆だと「4.8〜7.1％」で先に 7.1 が かな になり、(?=[0-9]) が外れて「〜」が
    #    記号のまま残る＝範囲が読まれない。下に陽性対照を置いた。
    t = re.sub(r"(?<=[0-9])\s*[〜~～]\s*(?=[0-9])", "から", t)

    # 小数の整数部が1桁の 4・7・9 は、**パーセントの前だけ** かなに開く
    # （2026-10-29 翔太さんの指定：「9.1」は きゅうてんいち。く と読まれていた）。
    # 🔴 「日」の前では開かない：9.9日→「きゅうてんきゅうにち」は "起遊転休日" と読まれた
    #    （2026-09-27 実測・下の陰性対照で固定している）。だから一般化せずパーセントだけ。
    # 🔑 自分で尺を測った結果は半々だった（speed 120・pitch -35、1モーラ≒110〜140ms）:
    #      「割合は9.1パーセントでした」 そのまま2.53 / きゅう2.64 / く2.51 ＝くに近い
    #      本番の行（…7,157めいで9.2パーセント…） そのまま10.60 / きゅう10.76 / く10.39 ＝きゅうに近い
    #      「割合は4.8パーセントでした」 そのまま2.61 / よん2.61 / し2.52 ＝よんに近い（＝元から正しい）
    #    ＝尺では決め切れない。かなに開いた形は起こしが「9.1%」「4.8%」と正しく戻るので、
    #      読みを固定する側に倒した。悪化はしないが「誤読を直した」とは言えない。
    # 🔑 範囲（4.8から7.1パーセント）では、**パーセントが付く右側だけ**が開く。
    #    左側（4.8）は数字のまま残す＝「パーセントの前だけ」という決まりを広げない
    #    （広げると 9.9日 と同じ型の事故に戻る。左側を開くかは耳の確認が要る）。
    t = re.sub(r"(?<![0-9.,])([479])\.([0-9]+)(?=パーセント)",
               lambda m: decimal_to_yomi(m.group(1), m.group(2)), t)

    # 助詞「は」が直後のかなと結合して「ha」と読まれる事故（死亡数は5年→"すうha"、
    # 政府はがん検診→"せいふ・わがん"）。読点を1つ入れて文節を切る＝緑さんの処方どおり。
    t = re.sub(r"(?<=[一-龥ー])は(?=[がか0-9])", "は、", t)
    t = re.sub(r"(?<=[一-龥ー])は(?=(?:いち|に|さん|よん|ご|ろく|なな|はち|きゅう|じゅう|ひゃく|せん|まん|おく|ちょう|ゼロ))",
               "は、", t)
    # 🔴 HARDWORDSでかなに開いた語が助詞「は」の直後に来ると、同じ "ha" の誤読が出る。
    #    台本750本をto_yomiに通すと、この形は13か所できる。4か所を実測して2つが誤読だった:
    #      「死亡率は人口千対で」→「…はじんこうせんたいで」＝"死亡率破…"（この語を足して作った穴）
    #      「多かったのはしんしっかん」＝"紳士官"（＝っ が落ちる・前からあった）
    #      「は、」を入れると、どちらも「わ」と書いた対照と同じ起こしになった。
    #    誤読が出なかった形（はほかの／ではびょうしょう／報告はおこなわれて）は触らない。
    #    過剰に一般化しない（は＋かな は普通の日本語に大量に出る）＝実測した語だけ当てる。
    #    上の2行と違い「直前が漢字」の条件は付けない。当てる先が語に決まっているので
    #    条件は穴になるだけ（台本に実在する形では一度も効かなかった）。
    t = re.sub(r"は(?=じんこうせんたい|しんしっかん)", "は、", t)

    # 助詞「へと」が "heto" と読まれる（緑さんメモ）
    t = re.sub(r"(?<=[一-龥ー])へと", "えと", t)

    # 台本に残った英単語（of / and / idea …）をカタカナへ。未知語は residual_latin で検品に回す。
    t = sub_english_words(t)

    # 英語の一字読みはしない（＝原稿生成側で日本語化する方針・2026-07-10 木内さん判断）。
    # 既知の頻出略語(ACRONYMS)だけカタカナ化済み。未知の英語はそのまま残し、LLM側で潰す。
    return unprotect_digits(t)


def to_yomi_english_only(text: str) -> str:
    """英語・略語だけをカタカナ/一字読みに変換し、数字・日付・漢字は原文のまま残す。
    ＝VOICEPEAKの抑揚エンジンに漢字と数字の読み判断を任せ、素読みされる英語だけ潰す方式。"""
    t = text.translate(str.maketrans("ＡＢＣＤＥＦＧＨＩＪＫＬＭＮＯＰＱＲＳＴＵＶＷＸＹＺ",
                                     "ABCDEFGHIJKLMNOPQRSTUVWXYZ"))
    return sub_acronyms(t)


