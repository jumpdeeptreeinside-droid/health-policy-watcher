# 略語は「英数字に挟まれていないとき」だけ置換する（2026-08-04）。
# 単純 replace だと AIDS→エーアイDS / UNAIDS→UNエーアイDS / WHOLE→ダブリューエイチオーLE と壊れた。
_ACRO_RE = re.compile("|".join(re.escape(k) for k in sorted(ACRONYMS, key=len, reverse=True)))


def sub_acronyms(text: str) -> str:
    def _rep(m):
        s, e = m.start(), m.end()
        prev = text[s - 1] if s > 0 else ""
        nxt = text[e] if e < len(text) else ""
        # 英字に挟まれているときだけ「長い英単語の一部」とみなす。数字が続くのは
        # WHA79・COVID19 のような略語＋番号なので置換してよい。
        if (prev and prev.isascii() and prev.isalpha()) or (nxt and nxt.isascii() and nxt.isalpha()):
            return m.group(0)
        return ACRONYMS[m.group(0)]
    return _ACRO_RE.sub(_rep, text)


