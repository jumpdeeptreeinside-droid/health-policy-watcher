_BIG = {"万": "まん", "億": "おく", "兆": "ちょう"}
_BIGV = {"万": 10**4, "億": 10**8, "兆": 10**12}


def group_units(n: int) -> str:
    """1008862000000 → "1兆88億6200万"。統計表の百万円単位を人が言う形に組み直す。"""
    out, rest = "", n
    for unit, v in (("兆", 10**12), ("億", 10**8), ("万", 10**4)):
        q, rest = divmod(rest, v)
        if q:
            out += f"{q}{unit}"
    if rest or not out:
        out += str(rest)
    return out


def big_yomi(numstr: str, unit: str) -> str:
    """「1兆」「1,453億」→ 読み。整数に戻してから読むので兆の音便が効く。"""
    return num_to_yomi(str(int(numstr.replace(",", "")) * _BIGV[unit]))

# 「本」は末尾の桁で ほん/ぼん/ぽん が変わる（16本＝じゅうろっぽん）。表では書けないので関数で。
_HON = {0: "ほん", 1: "いっぽん", 2: "にほん", 3: "さんぼん", 4: "よんほん", 5: "ごほん",
        6: "ろっぽん", 7: "ななほん", 8: "はっぽん", 9: "きゅうほん"}


def _hon_yomi(n: int) -> str:
    if n % 10 == 0:                       # 10本=じゅっぽん / 20本=にじゅっぽん
        return (num_to_yomi(str(n // 10)) if n >= 20 else "") + "じゅっぽん" if n < 100 \
            else num_to_yomi(str(n)) + "ほん"
    tens, ones = divmod(n, 10)
    return (num_to_yomi(str(tens * 10)) if tens else "") + _HON[ones]


_COUNTERS.append(("本", "ほん", _hon_yomi))


def _counter_yomi(numstr: str, big: str, base: str, irr: dict, surface: str = "") -> str:
    """数字(小数可)＋(万/億/兆)＋助数詞 → 読み。万・億・兆や小数が付くときは特殊読みを使わない。"""
    if "." in numstr:
        i, d = numstr.split(".", 1)
        return decimal_to_yomi(i, d) + (_BIG[big] if big else "") + base
    if big:
        return big_yomi(numstr, big) + base
    n = int(numstr.replace(",", ""))
    if callable(irr):
        return irr(n)
    if irr.get(n):                      # 表の特殊読み（ひとつ/ふつか…）が最優先
        return irr[n]
    if surface in EUPHONIC:             # 表に無い数は音便規則で作る（40歳→よんじゅっさい）
        e = _euphonic(n, base)
        if e:
            return e
    return num_to_yomi(numstr) + base


def apply_counters(t: str) -> str:
    for surface, base, irr in _COUNTERS:
        t = re.sub(r"([0-9][0-9,]*(?:\.[0-9]+)?)\s*(万|億|兆)?\s*" + re.escape(surface),
                   lambda m, b=base, i=irr, sf=surface: _short(_counter_yomi(m.group(1), m.group(2), b, i, sf),
                                                                  m.group(0)), t)
    return t


