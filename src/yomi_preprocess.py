# ---------- 「百」＋人／枚 の誤読つぶし（2026-09-18 → 2026-09-19 作り直し）----------
# 🔴 数字をかなに開かない方針（2026-08-21）は変えない。ここは**末尾の「N百＋助数詞」だけ**の例外。
#
# 直したい誤読: 600人 → ろっぴゃ「っ」にん。助数詞が「ひゃく」の直後に来ると促音化する。
#   ＝ 末尾がちょうど N00 のときだけ起きる。199人（…きゅうじゅうきゅうにん）では起きない。
#
# 🔴 かなに開く範囲を広げると別の誤読が出る（2026-09-19・VOICEPEAK合成＋whisperで実測）:
#     きゅうせんろっぴゃくまい → 「旧優先600枚」   ひゃくきゅうじゅうきゅうにん → 「飛躍99人」
#     ろっぴゃくにん           → 「6匹役人」       さんびゃくごじゅうはちまん… → 「3尾約58万」
#   かなの先頭が拗音・促音だとVOICEPEAKがそれを落とす。9/18版はこれを踏んでいた。
#
# ✅ 数字を頭に残し、最後の「N百＋助数詞」だけかなにすると全例で正しく読めた（実測）:
#     102万よんひゃくにん / 40万9千よんひゃくにん / 60万6千ひゃくにん / 9千ろっぴゃくまい
#     4万5千きゅうひゃくにん / 88万6千きゅうひゃくにん / 484万1千にひゃくにん
_FIX_COUNTERS = {"人": "にん", "枚": "まい", "歳": "さい"}


def _digits_with_units(rest: int) -> str:
    """かなの手前に置く「頭」を作る。1020000→"102万" / 409000→"40万9千" / 9000→"9千" / 0→""。

    🔴 末尾を「9000」のような裸の数字で終わらせない。直後のかなと地続きに読まれて
       「きゅうせん…」が先頭に来てしまい、拗音が落ちる（＝9/18版と同じ穴）。
    """
    if rest <= 0:
        return ""
    head = group_units(rest)                      # 例: "40万9000" / "102万"
    return re.sub(r"(\d+)000$", lambda m: m.group(1) + "千", head)


# ---------- 数字につく「人」は「名」で読ませる（2026-09-20・翔太さんの案）----------
# 「人」は助数詞として不規則すぎる:
#   600人→ろっぴゃ「っ」にん / 36人→さんじゅうろ「き」にん / 末尾1→「ひとり」
# 「名」は例外なく「めい」なので、数字につく助数詞を名に替えれば全部消える。
# VOICEPEAK合成＋whisperで確認済み: 36名 / 600名 / 101名 / 16201名 / 129436名 /
#                                   1020400名 / 1000000名 / 1名 … 全例そのまま読めた。
#
# 🔴 置き換えないもの: 「1人当たり」「1人前」「2人目」「3人組」「1人暮らし」など、
#    人が語の一部になっている形。「1名当たり」「1名前」は日本語として成立しない。
_NO_MEI_AFTER = "当たり|当り|あたり|前|目|組|分|部屋|暮ら|っ子|称|口|ずつ"
# 🔴 小数も拾う（2026-10-01 試聴指摘）。「1施設あたり9.2人」のような平均値が
#    整数パターンから漏れて「9.2にん」のまま残っていた。
_MEI_RE = re.compile(r"(?<![0-9,.])([0-9][0-9,]*(?:\.[0-9]+)?)人(?!" + _NO_MEI_AFTER + ")")


def counter_nin_to_mei(t: str) -> str:
    # 🔴 漢字の「名」は「な」と読まれることがある（2026-09-21 試聴指摘）。
    #    かなで「めい」と書けば曖昧さが残らない（数字が前にあるので拗音落ちも起きない）。
    return _MEI_RE.sub(lambda m: m.group(1) + "めい", t)


def fix_hyaku_counters(t: str) -> str:
    def rep(m):
        raw, unit = m.group(1), m.group(2)
        n = int(raw.replace(",", ""))
        h = (n % 1000) // 100
        if n % 100 == 0 and h:                    # 末尾がN00 → 助数詞が「ひゃく」に貼りつく
            return _digits_with_units(n - h * 100) + num_to_yomi(str(h * 100)) + _FIX_COUNTERS[unit]
        return m.group(0)
    return re.sub(r"(?<![0-9,.])([0-9][0-9,]*)(" + "|".join(_FIX_COUNTERS) + ")", rep, t)


# ---------- 「百」＋床／歳 の詰まる音つぶし（2026-10-31 試聴指摘・翔太さん）----------
# 誤読: 200床 → 「にひゃ"っ"しょう」 ／ 100歳以上 → 「ひゃ"っ"さい以上」。
# 上の人／枚と同じ型で、助数詞が「ひゃく」の直後に来ると促音化する。
#
# 🔴 上の人／枚と違い、**数字は数字のまま残して助数詞だけかなにする**。
#    全部かなに開くと拗音が落ちる（2026-10-31 実測・本番の設定で合成→mlx_whisperで起こし）:
#      「…びょうしょう数にひゃくしょう以上の…」→ 起こし "病床数に100床以上"（＝「に」が切れた）
#      「…びょうしょう数200しょう以上の…」    → 起こし "病床数200床以上"（尺も 9.72 / そのまま 9.70）
#    ＝数字を頭に残す形だけが崩れなかった（9/19に人／枚で確かめたのと同じ結論）。
#
# 🔴 末尾がちょうどN00のときだけ当てる。VOICEPEAK自身が持っている正しい音便を壊さない:
#      1歳=いっさい / 8歳=はっさい / 10歳=じゅっさい / 5歳以上10歳未満（この回の台本にある）
#    百の位の音便（300=さんびゃく / 600=ろっぴゃく / 800=はっぴゃく）は、数字を数字のまま
#    渡すので VOICEPEAK 側で作られる＝こちらでは触らない（実測で起こしが「300床」等に戻る）。
#
# 🔑 この誤読は尺では測れない。にひゃくしょう／にひゃっしょう はどちらも5モーラで、
#    起こしもどちらも「200床」に正規化される（2026-10-31 実測）。よりどころは翔太さんの耳で、
#    こちらで確かめられるのは「渡す文が狙った形になっていること」と「悪化していないこと」まで。
# 🔴 2026-11-04 翔太さんの耳：**「歳」は数字を残す形では直っていなかった**。
#    「100さい」と書いても「ひゃ"っ"さい」のままだった（見本の6番）。
#    ＝100 の読み「ひゃく」を VOICEPEAK 自身が作る間に音便が入るので、こちらから止められない。
#    → 歳は「人／枚」と同じ形（百の位もかなに開く）に移した＝「ひゃくさい」。
#      こう書けば**数字が無いので音便を作る材料が無い**。狙いの読みは「ひゃくさい」。
#    🔑 床（5番）は数字を残す形で翔太さんの耳を通ったので、そのままにする。
#      床で全部かなに開くと拗音が落ちた実測（上のコメント）があるため、歳だけを移す。
